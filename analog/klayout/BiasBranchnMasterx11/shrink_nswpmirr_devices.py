def main() -> None:
    text = MAG_PATH.read_text()
    lines = text.splitlines()
    changed = 0
    missing: list[str] = []

    for old, new in REPLACEMENTS.items():
        found = False
        for i, line in enumerate(lines):
            if line == old:
                lines[i] = new
                changed += 1
                found = True
        if not found:
            missing.append(old)

    if missing:
        raise SystemExit(f"Missing {len(missing)} expected rect lines:\n" + "\n".join(missing))

    MAG_PATH.write_text("\n".join(lines) + "\n")
    print(f"Updated {changed} rectangles in {MAG_PATH.name}")


if __name__ == "__main__":
    main()
